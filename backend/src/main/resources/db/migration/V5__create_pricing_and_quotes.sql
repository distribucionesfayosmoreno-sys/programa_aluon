CREATE TABLE IF NOT EXISTS tariffs (
    id UUID PRIMARY KEY,
    tenant_id UUID NOT NULL,
    code VARCHAR(50) NOT NULL UNIQUE,
    label VARCHAR(120) NOT NULL,
    auto_approval BOOLEAN NOT NULL DEFAULT FALSE,
    is_default BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE IF NOT EXISTS tariff_prices (
    id UUID PRIMARY KEY,
    tenant_id UUID NOT NULL,
    tariff_id UUID NOT NULL REFERENCES tariffs(id) ON DELETE CASCADE,
    door_model VARCHAR(32) NOT NULL,
    door_type VARCHAR(32) NOT NULL,
    price_per_m2 NUMERIC(12, 2) NOT NULL,
    UNIQUE (tariff_id, door_model, door_type)
);

CREATE TABLE IF NOT EXISTS quote_requests (
    id UUID PRIMARY KEY,
    tenant_id UUID NOT NULL,
    quote_number VARCHAR(40) NOT NULL UNIQUE,
    customer_id UUID NOT NULL REFERENCES customers(id),
    tariff_code VARCHAR(50),
    contact_email VARCHAR(160),
    contact_whatsapp VARCHAR(40),
    status VARCHAR(32) NOT NULL,
    validation_mode VARCHAR(16) NOT NULL,
    channel VARCHAR(16) NOT NULL,
    total NUMERIC(12, 2) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    validated_at TIMESTAMP,
    sent_at TIMESTAMP
);

CREATE TABLE IF NOT EXISTS quote_items (
    id UUID PRIMARY KEY,
    tenant_id UUID NOT NULL,
    quote_request_id UUID NOT NULL REFERENCES quote_requests(id) ON DELETE CASCADE,
    door_model VARCHAR(32) NOT NULL,
    door_type VARCHAR(32) NOT NULL,
    width_mm INTEGER NOT NULL,
    height_mm INTEGER NOT NULL,
    m2 NUMERIC(12, 4) NOT NULL,
    price_per_m2 NUMERIC(12, 2) NOT NULL,
    line_total NUMERIC(12, 2) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_quote_requests_customer_id ON quote_requests(customer_id);
CREATE INDEX IF NOT EXISTS idx_quote_requests_status ON quote_requests(status);

